import base64
import binascii
import secrets
import time
from pathlib import Path

from aiohttp import web
from jinja2 import Environment, FileSystemLoader, select_autoescape

from .config import validate_models
from .editorial import metadata, recorded_context
from .feeds import item_images, item_videos, parse_opml
from .formatting import duration_label
from .version import VERSION
from .controls import HELP_SECTIONS
from .publishing import model_label
from .quotas import provider_reset_line


def create_app(config, store, pool, signal, engine):
    env = Environment(loader=FileSystemLoader(Path(__file__).parent / "templates"), autoescape=select_autoescape())
    env.filters["when"] = lambda value: time.strftime("%m-%d %H:%M UTC", time.gmtime(value)) if value else "never"
    env.filters["model_label"] = lambda row: model_label(row, exact=True)
    env.filters["duration"] = duration_label

    @web.middleware
    async def secure(request, handler):
        authenticated = False
        try:
            scheme, encoded = request.headers.get("Authorization", "").split(" ", 1)
            user, password = base64.b64decode(encoded, validate=True).decode().split(":", 1)
            authenticated = scheme.lower() == "basic" and secrets.compare_digest(user.encode(), b"admin") and secrets.compare_digest(password.encode(), config.data["dashboard_password"].encode())
        except (ValueError, UnicodeError, binascii.Error):
            pass
        if not authenticated:
            return web.Response(status=401, text="Authentication required", headers={"WWW-Authenticate": 'Basic realm="Signal News Bot", charset="UTF-8"'})
        if request.method == "POST":
            if engine.maintenance:
                raise web.HTTPServiceUnavailable(text="Update/maintenance in progress. Try again shortly.")
            data = await request.post()
            if not secrets.compare_digest(str(data.get("csrf", "")).encode(), config.data["csrf"].encode()):
                raise web.HTTPForbidden(text="Invalid CSRF token")
        try:
            response = await handler(request)
        except web.HTTPException as exc:
            response = exc
        except (ValueError, KeyError, TypeError) as exc:
            # Validation messages are generated by us, never echo API responses or secrets.
            response = web.Response(status=400, text="Invalid input. " + (str(exc) if isinstance(exc, ValueError) else "Check form fields."))
        response.headers.update({"Cache-Control": "no-store", "X-Content-Type-Options": "nosniff",
            "Referrer-Policy": "no-referrer", "X-Frame-Options": "DENY",
            "Content-Security-Policy": "default-src 'none'; style-src 'unsafe-inline'; form-action 'self'; frame-ancestors 'none'; base-uri 'none'"})
        if isinstance(response, web.HTTPException):
            raise response
        return response

    app = web.Application(middlewares=[secure], client_max_size=3_000_000)

    async def index(request):
        selected = request.query.get("status", "")
        page = "help" if request.path == "/help" else request.query.get("page", "news" if selected else "overview")
        if page not in {"overview", "news", "feeds", "models", "settings", "help"}:
            raise ValueError("Unknown dashboard section.")
        number = max(1, min(100000, int(request.query.get("n", "1"))))
        states = {"queued", "baseline", "skipped", "preview", "outbox", "sent", "uncertain", "expired"}
        items, models, quotas, counts, events, failed_feeds, visible_feeds = [], [], [], {}, [], [], []
        storage, feed_total, failed_total, feed_matches = {}, 0, 0, 0
        search = request.query.get("q", "")[:200]
        if page in {"news", "overview"}:
            columns = ("id,status,published,sent_at,score,model,title,url,summary,reason,quota,provider,actual_model,decision,route,"
                       "image_url,image_urls,video_urls,video_page,media_result,"
                       "(SELECT state FROM withdrawals WHERE item_id=items.id) AS withdrawal")
            where, params = ("WHERE status=?", (selected,)) if selected in states and page == "news" else ("", ())
            cap, offset = (5, 0) if page == "overview" else (60, (number - 1) * 60)
            items = store.rows(f"SELECT {columns} FROM items {where} ORDER BY id DESC LIMIT ? OFFSET ?", (*params, cap, offset))
            for row in items:
                clips, page_url = item_videos(row)
                row["media"] = {"photos_found": len(item_images(row)), "video_found": bool(clips or page_url),
                                **metadata(row, "media_result")}
                row["editor_context"] = recorded_context(row)
            counts = {r["status"]: r["n"] for r in store.rows("SELECT status,COUNT(*) AS n FROM items GROUP BY status")}
        if page in {"overview", "feeds"}:
            totals = store.one("SELECT COUNT(*) AS n,COUNT(CASE WHEN error!='' THEN 1 END) AS failed FROM feeds WHERE removed=0")
            feed_total, failed_total = totals["n"], totals["failed"]
        if page == "overview":
            if failed_total:
                failed_feeds = store.rows("SELECT title,error FROM feeds WHERE removed=0 AND error!='' ORDER BY title LIMIT 5")
            events = store.rows("SELECT at,kind,detail FROM events ORDER BY id DESC LIMIT 15")
        if page == "feeds":
            needle = search.lower()
            condition = "removed=0 AND (?='' OR instr(lower(title || ' ' || url),?)>0)"
            feed_matches = (store.one(f"SELECT COUNT(*) AS n FROM feeds WHERE {condition}", (needle, needle))["n"]
                            if needle else feed_total)
            visible_feeds = store.rows(f"SELECT * FROM feeds WHERE {condition} ORDER BY title,id LIMIT 50 OFFSET ?",
                                       (needle, needle, (number - 1) * 50))
        if page in {"models", "settings"}:
            fields = {"name", "provider", "model", "daily_requests", "enabled", "json_mode", "account_id"}
            models = [{k: v for k, v in m.items() if k in fields} for m in config.data["models"]]
        if page == "models":
            quotas = pool.status()
            for q in quotas:
                q["reset"] = provider_reset_line(q["provider"], pool.quota_view(q["name"])["quota"])
                q["attempts"] = store.usage(q["name"])
        elif page == "settings":
            storage = store.storage()
        html = env.get_template("index.html").render(c=config.data, models=models, quotas=quotas,
            feed_total=feed_total, failed_total=failed_total, failed_feeds=failed_feeds, maintenance=engine.maintenance,
            items=items, states=sorted(states), selected=selected, page=page, version=VERSION, number=number, search=search,
            visible_feeds=visible_feeds, feed_matches=feed_matches, counts=counts, storage=storage, help_sections=HELP_SECTIONS,
            events=events, pool_error=engine.pool_error,
            connected=signal.connected, csrf=config.data["csrf"])
        return web.Response(text=html, content_type="text/html")

    async def settings(request):
        data = await request.post()
        group = str(data.get("group_id", "")).strip()
        if group:
            try:
                if len(base64.b64decode(group, validate=True)) != 32:
                    raise ValueError()
            except (ValueError, binascii.Error):
                raise ValueError("Group ID must be the base64 ID shown by signal-cli listGroups.")
        threshold, rate, age = int(data["threshold"]), int(data["max_posts_per_hour"]), int(data["max_age_hours"])
        preferred, mode = str(data["preferred_model"]), str(data["mode"])
        if not 0 <= threshold <= 100 or not 1 <= rate <= 300 or not 1 <= age <= 48:
            raise ValueError("Settings out of range.")
        if preferred not in {"auto", *(m["name"] for m in config.data["models"])} or mode not in {"preview", "live"}:
            raise ValueError("Invalid model or mode.")
        account = str(data.get("signal_account", "")).strip()
        if len(account) > 64 or any(c not in "+-0123456789abcdefABCDEF" for c in account):
            raise ValueError("Signal account must be a phone number or account UUID, or blank for the only account.")
        config.update(focus=str(data["focus"])[:2000], exclude=str(data["exclude"])[:2000], threshold=threshold,
            group_id=group, signal_account=account, preferred_model=preferred, mode=mode,
            max_posts_per_hour=rate, max_age_hours=age, paused="paused" in data,
            fallback="fallback" in data, include_sources="include_sources" in data)
        store.event("config", "Dashboard settings updated")
        raise web.HTTPSeeOther("/?page=settings")

    async def preferences(request):
        data = await request.post()
        config.update(summary_length=str(data["summary_length"]), footer_model="footer_model" in data,
            footer_usage="footer_usage" in data, footer_age="footer_age" in data,
            footer_hourly="footer_hourly" in data, footer_score="footer_score" in data,
            include_images="include_images" in data, topic_feedback="topic_feedback" in data,
            image_min_score=int(data.get("image_min_score", config.data["image_min_score"])),
            include_videos="include_videos" in data,
            video_min_score=int(data.get("video_min_score", config.data["video_min_score"])),
            feedback_weight=int(data.get("feedback_weight", config.data["feedback_weight"])),
            reply_cleanup="reply_cleanup" in data, story_mute="story_mute" in data,
            retention_articles_days=int(data["retention_articles_days"]),
            retention_history_days=int(data["retention_history_days"]),
            backup_retention_days=int(data["backup_retention_days"]), backup_keep=int(data["backup_keep"]),
            backup_prune_enabled="backup_prune_enabled" in data)
        if not config.data["reply_cleanup"]:
            store.execute("DELETE FROM reply_removals")
        engine.cleanup_previews.clear()
        store.event("config", "Dashboard display and retention preferences updated")
        raise web.HTTPSeeOther("/?page=settings")

    async def search(request):
        data = await request.post()
        if "clear" in data:
            config.update(tavily_key="", web_expand=False)
        else:
            key = str(data.get("tavily_key", "")).strip() or config.data["tavily_key"]
            if "web_expand" in data and not key:
                raise ValueError("Enter a Tavily API key before enabling web details.")
            config.update(tavily_key=key, web_expand="web_expand" in data)
        store.event("config", "Web expansion settings updated")
        raise web.HTTPSeeOther("/?page=settings")

    async def command(request):
        data = await request.post()
        body = str(data.get("command", ""))
        if body.partition(" ")[0] not in {"/cleanup", "/refresh", "/feed", "/summary"}:
            raise ValueError("Unsupported dashboard action.")
        result = await engine.command(body)
        parent = "feeds" if body.startswith("/feed ") else "news" if body.startswith("/summary") else "settings"
        confirm = "/cleanup confirm" if body == "/cleanup preview" else "/feed confirm" if body.startswith("/feed remove ") else ""
        html = env.get_template("result.html").render(result=result, confirm=confirm, csrf=config.data["csrf"],
                                                       version=VERSION, page=parent)
        return web.Response(text=html, content_type="text/html")

    async def subscribe(request):
        data = await request.post()
        result = await engine.command("/feed add " + str(data.get("url", "")).strip())
        html = env.get_template("result.html").render(result=result, version=VERSION, page="feeds")
        return web.Response(text=html, content_type="text/html")

    async def model(request):
        data = await request.post()
        name = str(data["name"])
        models = [dict(m) for m in config.data["models"]]
        old = next((m for m in models if m["name"] == name), {})
        models = [m for m in models if m["name"] != name]
        if data.get("action") != "delete":
            entry = {"name": name, "provider": str(data["provider"]), "model": str(data["model"]).strip(),
                "account_id": str(data.get("account_id", "")).strip(),
                "key": str(data.get("key", "")).strip() or (old.get("key", "") if old.get("provider") == data["provider"] else ""),
                "daily_requests": int(data["daily_requests"]), "enabled": "enabled" in data, "json_mode": "json_mode" in data}
            # Preserve routing priority when editing an existing entry.
            if old:
                position = next(i for i, m in enumerate(config.data["models"]) if m["name"] == name)
                models.insert(position, entry)
            else:
                models.append(entry)
        validate_models(models)
        updates = {"models": models}
        if config.data["preferred_model"] not in {"auto", *(m["name"] for m in models)}:
            updates["preferred_model"] = "auto"
        config.update(**updates)
        store.set_model_state(name, quota={})
        store.event("config", "Model configuration updated")
        raise web.HTTPSeeOther("/?page=models")

    async def upload(request):
        data = await request.post()
        upload = data.get("opml")
        if not isinstance(upload, web.FileField):
            raise ValueError("Select an OPML file.")
        feeds = parse_opml(upload.file.read(3_000_001))
        added = sum(store.add_feed(url, title, config.data["poll_seconds"]) for url, title in feeds)
        store.event("feeds", f"OPML imported: {added} new subscriptions. First fetch establishes baseline, not a news flood.")
        raise web.HTTPSeeOther("/?page=feeds")

    async def feed(request):
        data = await request.post()
        interval, enabled = int(data["interval"]), "enabled" in data
        if not 60 <= interval <= 86400:
            raise ValueError("Feed interval must be 60..86400 seconds.")
        feed_id, instant = int(request.match_info["id"]), "instant" in data
        store.execute("""UPDATE feeds SET interval=?,enabled=?,instant=?,
                      next_poll=CASE WHEN error='' THEN MIN(next_poll,?) ELSE next_poll END WHERE id=? AND removed=0""",
                      (interval, int(enabled), int(instant), time.time() + interval, feed_id))
        if not instant:
            store.requeue_direct("instant", feed_id)
        raise web.HTTPSeeOther("/?page=feeds")

    async def action(request):
        data = await request.post()
        action = str(data["action"])
        if action == "sample":
            rows = store.rows("""SELECT i.id FROM items i JOIN feeds f ON i.feed_id=f.id
                WHERE f.removed=0 AND i.status='baseline' AND i.published>? ORDER BY i.published DESC LIMIT 5""",
                              (time.time() - config.data["max_age_hours"] * 3600,))
            # Sample never enables live posting, even if the operator was previously live.
            config.update(mode="preview")
            for row in rows:
                store.update_item(row["id"], status="queued")
            store.event("config", f"Queued {len(rows)} baseline samples; switched to preview mode")
        elif action in {"retry", "dismiss", "approve"}:
            item_id = int(data["id"])
            item = store.one("SELECT * FROM items WHERE id=?", (item_id,))
            if not item:
                raise ValueError("Item not found.")
            if action in {"approve", "retry"} and store.one("SELECT id FROM feeds WHERE id=? AND removed=1", (item["feed_id"],)):
                raise ValueError("Feed was removed. Re-add it before retrying its articles.")
            if action == "approve":
                if item["status"] != "preview" or not engine.route_current(item):
                    raise ValueError("Only a preview that matches current delivery settings can be approved.")
                store.update_item(item_id, status="outbox")
            elif action == "retry":
                if item["status"] in {"sent", "sending"}:
                    raise ValueError("Cannot requeue sent or in-flight items.")
                store.update_item(item_id, status="queued", route="")
            else:
                if item["status"] in {"sent", "sending"}:
                    raise ValueError("Cannot dismiss sent or in-flight items.")
                store.update_item(item_id, status="skipped", reason="Dismissed by dashboard operator")
        else:
            raise ValueError("Unknown action.")
        raise web.HTTPSeeOther("/?page=news")

    async def groups(request):
        try:
            groups = await signal.rpc("listGroups")
        except Exception:
            return web.Response(status=503, text="Cannot contact signal-cli. Check its service and linked account.")
        return web.Response(text=env.get_template("groups.html").render(groups=groups, version=VERSION, page="settings"), content_type="text/html")

    async def health(request):
        return web.json_response({"version": VERSION, "signal_connected": signal.connected, "mode": config.data["mode"], "pool_error": engine.pool_error, "maintenance": engine.maintenance})

    async def catalog(request):
        try:
            models = await pool.free_catalog()
        except Exception:
            return web.Response(status=503, text="Cannot load the free catalog. Existing configuration is unchanged.")
        return web.Response(text=env.get_template("catalog.html").render(models=models, version=VERSION, page="models"), content_type="text/html")

    app.add_routes([web.get("/", index), web.get("/help", index), web.post("/settings", settings), web.post("/model", model),
                    web.post("/search", search),
                    web.post("/preferences", preferences), web.post("/command", command),
                    web.post("/import", upload), web.post("/feeds/add", subscribe), web.post("/feeds/{id}", feed),
                    web.post("/action", action),
                    web.get("/groups", groups), web.get("/health", health), web.get("/catalog", catalog)])
    return app
